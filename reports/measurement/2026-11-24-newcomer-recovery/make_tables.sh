#!/bin/sh
# Regenerate TABLES.md from results-2/ (new) and results/ (base, head, and slice: the code before E2 failed): make_tables.sh
# Any Python 3.11+ will do; nothing is measured.
cd "$(dirname "$0")" || exit 1
PY="${PYTHON:-python3} -B"
N="n0-churn-own n0c-fixed-own n1-churn-others n1c-fixed-others n2-fixed-all"
two() { for f in $1; do printf 'results-2/%s.json results/%s.json ' "$f" "$f"; done; }
{
echo "# Tables, generated by make_tables.sh"
echo; echo "Trees: \`new\` is \`72db59fafb92b9630e1524e0e08b99a21cdda81f\` (results-2/); \`base\` \`966857bb070a1973e6974d56ed1dd37dcd9409b7\` and \`head\` \`a0862c3eeb0b84236661451ca5c3d00127536d27\` (results/); \`slice\` \`d49645b3fb75b46497e3049cbe65424a6c690e34\`, the code before E2 failed (results/). Every run: cryptography 50.0.1."
echo; echo "## N0-N2 by the harness: every run, the underdriven ones too"; echo
for f in $N; do $PY verdict_table.py $(two $f) new,base,slice; echo; done
echo "## N0-N2 by 🌫's comparator (hardened): INVALID runs named, cells complete or not"; echo
(cd comparator; for f in $N; do $PY judge_rows.py ../results-2/$f.json ../results/$f.json; echo; done)
echo "## N0c-N2: the worst first frame beside the bound"; echo
$PY bounds_table.py $(two "n0c-fixed-own n1-churn-others n1c-fixed-others n2-fixed-all") new,base,slice
echo; echo "## N0: copies sent until one was heard, against the lottery"; echo
$PY copies.py $(two n0-churn-own) new,base,slice
echo; echo "## E1: #171's rows, scaled"; echo
$PY established_table.py results-2/established.json results/established.json
echo; echo "## E2: #171's rows at full length (new), and the run of d49645b that failed (slice)"; echo
(cd comparator; $PY judge_rows.py ../results-2/full/new/run* ../results/full/slice/run*)
echo; echo "## E3: pass 2's scaled rows"; echo
mkdir -p .scaled && cp results-2/scaled-new.json results/scaled-base.json results/scaled-slice.json .scaled/ && $PY scaled_compare.py .scaled new,base,slice; rm -rf .scaled
echo; echo "## I: the inverse rows"; echo
$PY inverse_table.py results-2/inverse.json results/inverse.json
echo; echo "## J, J-all: established stations in junk and forgeries"; echo
$PY junk_table.py results-2/junk.json results/junk.json
echo; echo "## W: #177 at the daemon (check budgets lifted; on a0862c3 with and without 🕯's commit)"; echo
$PY verdict_table.py results/w-177.json nobudget-177,nobudget
(cd comparator; echo; $PY judge_rows.py ../results/w-177.json)
echo; echo "## J in virtual time (junk_model.py)"; echo
cat results/junk-model.md
echo; echo "## AB: the share dropped at the socket, 60 s flat out (diagnostic)"; echo; echo '```'; cat results/ab.log; echo '```'
} > TABLES.md 2>&1
