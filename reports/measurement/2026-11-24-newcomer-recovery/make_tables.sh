#!/bin/sh
# Regenerate TABLES.md from results/: make_tables.sh   (needs no cryptography; run it with any Python 3.11+)
cd "$(dirname "$0")" || exit 1
PY="${PYTHON:-python3} -B"
N="results/n0-churn-own.json results/n0c-fixed-own.json results/n1-churn-others.json results/n1c-fixed-others.json results/n2-fixed-all.json"
{
echo "# Tables, generated by make_tables.sh from results/"
echo; echo "Trees: \`slice\` is \`d49645b3fb75b46497e3049cbe65424a6c690e34\`, \`base\` \`966857bb070a1973e6974d56ed1dd37dcd9409b7\`, \`head\` \`a0862c3eeb0b84236661451ca5c3d00127536d27\`. Every run: cryptography 50.0.1."
echo; echo "## N0-N2: the harness's verdict per cell, every run, the underdriven ones too"; echo
for f in $N; do $PY verdict_table.py "$f" slice,base; echo; done
echo "## N0-N2: 🌫's comparator (hardened), INVALID runs named, cells completed"; echo
(cd comparator; for f in $N; do $PY judge_rows.py "../$f"; echo; done)
echo "## N0c-N2: the worst first frame beside the bound"; echo
$PY bounds_table.py $N slice,base
echo; echo "## N0: copies sent until one was heard, against the lottery"; echo
$PY copies.py results/n0-churn-own.json slice,base
echo; echo "## W: #177 at the daemon (budgets lifted)"; echo
$PY verdict_table.py results/w-177.json nobudget-177,nobudget
(cd comparator; echo; $PY judge_rows.py ../results/w-177.json)
echo; echo "## E1: #171's rows, scaled"; echo
$PY established_table.py results/established.json
echo; echo "## E2: #171's rows at full length"; echo
(cd comparator; $PY judge_rows.py ../results/full/slice/run*)
echo; echo "## E3: pass 2's scaled rows"; echo
$PY scaled_compare.py results slice,base
echo; echo "## J, J-all: established stations in junk and forgeries"; echo
$PY junk_table.py results/junk.json
echo; echo "## I: the inverse rows"; echo
$PY inverse_table.py results/inverse.json
echo; echo "## J in virtual time"; echo
cat results/junk-model.md
} > TABLES.md 2>&1
