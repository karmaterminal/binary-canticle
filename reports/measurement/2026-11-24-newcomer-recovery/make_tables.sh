#!/bin/sh
# Regenerate TABLES.md: make_tables.sh. Three sets: results-3/ (fix, the code that would merge), results-2/ (new, 72db59f) and results/
# (base, head, and slice: d49645b, the code before E2 failed). A file of a set that has not run yet is left out. Any Python 3.11+ will
# do; nothing is measured.
cd "$(dirname "$0")" || exit 1
PY="${PYTHON:-python3} -B"
N="n0-churn-own n0c-fixed-own n1-churn-others n1c-fixed-others n2-fixed-all"
there() { for f in "$@"; do [ -e "$f" ] && printf '%s ' "$f"; done; }
three() { for f in $1; do there "results-3/$f.json" "results-2/$f.json" "results/$f.json"; done; }
{
echo "# Tables, generated by make_tables.sh"
echo; echo "Trees: \`fix\` is \`91d36c608bda8c6efa9f0c602366fdf3491a40ce\` (results-3/; its intake.py is \`dfa0414\`'s); \`new\` \`72db59fafb92b9630e1524e0e08b99a21cdda81f\` (results-2/); \`base\` \`966857bb070a1973e6974d56ed1dd37dcd9409b7\` and \`head\` \`a0862c3eeb0b84236661451ca5c3d00127536d27\` (results/); \`slice\` \`d49645b3fb75b46497e3049cbe65424a6c690e34\`, the code before E2 failed (results/). Every run: cryptography 50.0.1."
echo; echo "## N0-N2 by the harness: every run, the underdriven ones too"; echo
for f in $N; do $PY verdict_table.py $(three $f) fix,new,base,slice; echo; done
echo "## N0-N2 by 🌫's comparator (hardened): INVALID runs named, cells complete or not"; echo
(cd comparator; for f in $N; do $PY judge_rows.py $(cd .. && there results-3/$f.json results-2/$f.json results/$f.json | sed 's#results#../results#g'); echo; done)
echo "## N0c-N2: the worst first frame beside the bound"; echo
$PY bounds_table.py $(three "n0c-fixed-own n1-churn-others n1c-fixed-others n2-fixed-all") fix,new,base,slice
echo; echo "## N0: copies sent until one was heard, against the lottery"; echo
$PY copies.py $(three n0-churn-own) fix,new,base,slice
echo; echo "## E1: #171's rows, scaled"; echo
$PY established_table.py $(there results-3/established.json results-2/established.json results/established.json)
echo; echo "## E2: #171's rows at full length (fix, new), and the run of d49645b that failed (slice)"; echo
(cd comparator; $PY judge_rows.py $(cd .. && there results-3/full/fix/run* results-2/full/new/run* results/full/slice/run* | sed 's#results#../results#g'))
echo; echo "## E3: pass 2's scaled rows"; echo
mkdir -p .scaled && cp $(there results-3/scaled-fix.json results-2/scaled-new.json results/scaled-base.json results/scaled-slice.json) .scaled/ &&
  $PY scaled_compare.py .scaled $(for t in fix new base slice; do [ -e .scaled/scaled-$t.json ] && printf '%s\n' $t; done | paste -sd,); rm -rf .scaled
echo; echo "## I: the inverse rows"; echo
$PY inverse_table.py $(there results-3/inverse.json results-2/inverse.json results/inverse.json)
echo; echo "## J, J-all: established stations in junk and forgeries"; echo
$PY junk_table.py $(there results-3/junk.json results-2/junk.json results/junk.json)
echo; echo "## W: #177 at the daemon (check budgets lifted; on a0862c3 with and without 🕯's commit)"; echo
$PY verdict_table.py results/w-177.json nobudget-177,nobudget
(cd comparator; echo; $PY judge_rows.py ../results/w-177.json)
echo; echo "## J in virtual time (junk_model.py)"; echo
cat results/junk-model.md
echo; echo "## offer()'s cost per datagram (bench_offer.py, a diagnostic): the minimum of the runs, µs, and their median"; echo
$PY bench_table.py results-3/bench-offer.log
echo; echo "## AB, results-3/ (fix against new): what the reader read a second, 60 s flat out (diagnostic)"; echo
$PY ab_table.py results-3/ab
for ab in results-3/ab.log results/ab.log; do [ -e $ab ] || continue
  echo; echo "## AB, $(dirname $ab)/: the share dropped at the socket, 60 s flat out (diagnostic)"; echo; echo '```'; cat $ab; echo '```'; done
} > TABLES.md 2>&1
