"""Writes TABLES.md: PLAN.md's per-cell report for every newcomer row, by newcomer_table.py (first frames per run, item distribution, misses, drops,
refusals, the flood's lowest second). Usage: make_tables.py"""

import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROWS = [("Row 0, churn-40 (deciding)", ["recovery-churn.json"], "head,base,narrow,nobudget"),
        ("Row 0c, fixed-40 (companion reading)", ["recovery-fixed.json"], "head,base"),
        ("Row 1, saturation, churned", ["saturation-churn.json"], "head,base"),
        ("Row 1c, saturation, ports held open", ["saturation-fixed.json"], "head,base"),
        ("Rows 1s and 1r, an even sender and 200 000/s", ["saturation-extra.json"], "head"),
        ("Row 1h, the newcomer on another address", ["otherhost.json"], "head,base"),
        ("Row 2, attribution (toggles of the head)", ["attribution.json"], "a,a-lanes,a-budgets,b,c"),
        ("Row 2w, nobudget with the wake collapsed (diagnostic)", ["recovery-wake.json"], "nobudget-wake")]
out = ["# Every newcomer row, per cell", "",
       "Generated by `make_tables.py` from `results/`; the columns are PLAN.md's. Cryptography 50.0.1 in every run. A lost item counts as infinite.", ""]
for title, files, trees in ROWS:
    p = subprocess.run([sys.executable, "-B", str(HERE / "newcomer_table.py"), *[str(HERE / "results" / f) for f in files], trees],
                       capture_output=True, text=True, check=True)
    out += [f"## {title}", "", p.stdout.rstrip("\n"), ""]
(HERE / "TABLES.md").write_text("\n".join(out))
print(len(out), "lines")
